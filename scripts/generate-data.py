#!/usr/bin/env python3
"""Generate the web demo's data files from the voice project's assets.

Nothing in /Users/heyya/voice is modified: the two tigers recording is only read,
and the already published analysis (liang-zhi-lao-hu.json) is re-shaped for the
browser.

Outputs (written next to this script's parent directory):
  data/song-data.js    note timeline + energy envelope, consumed by index.html
  data/audio-data.js   base64 copy of the recording, used only when the plain
                       <audio src="audio/..."> path is blocked (file:// in some
                       browsers); loaded lazily by app.js.

The envelope mirrors what AVAudioPlayer reports to ExperienceModel.tick():
averagePower (RMS in dBFS) and peakPower, sampled once per display frame
(1/60 s), taking the loudest channel — the same `.max()` the Swift code uses.
"""

import base64
import json
import os
import subprocess
import sys
import wave

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICE = "/Users/heyya/voice"
SOURCE_MP3 = os.path.join(VOICE, "两只老虎.mp3")
SOURCE_ANALYSIS = os.path.join(VOICE, "voice", "Resources", "KnownSongs", "liang-zhi-lao-hu.json")
WORK_WAV = "/tmp/liang-zhi-lao-hu-meter.wav"

FRAME_RATE = 60.0
FLOOR_DB = -160.0


def decode(path):
    subprocess.run(
        ["afconvert", "-f", "WAVE", "-d", "LEI16@44100", "-c", "2", path, WORK_WAV],
        check=True,
        capture_output=True,
    )
    with wave.open(WORK_WAV, "rb") as handle:
        channels = handle.getnchannels()
        width = handle.getsampwidth()
        rate = handle.getframerate()
        raw = handle.readframes(handle.getnframes())
    assert width == 2, width
    samples = np.frombuffer(raw, dtype="<i2").astype(np.float64) / 32768.0
    samples = samples.reshape(-1, channels).T  # channel-major
    return samples, rate


def to_db(linear):
    return np.maximum(FLOOR_DB, 20.0 * np.log10(np.maximum(linear, 1e-8)))


def envelope(samples, rate):
    step = int(round(rate / FRAME_RATE))
    count = samples.shape[1] // step
    trimmed = samples[:, : count * step]
    windows = trimmed.reshape(samples.shape[0], count, step)

    # The Swift tick takes the loudest channel for both meters.
    rms = np.sqrt((windows ** 2).mean(axis=2))          # channels × frames
    peak = np.abs(windows).max(axis=2)
    average_db = to_db(rms).max(axis=0)
    peak_db = to_db(peak).max(axis=0)

    # A meter never reports a peak below the window's RMS.
    peak_db = np.maximum(peak_db, average_db)

    def pack(values):
        return [round(float(v), 1) for v in values]

    return pack(average_db), pack(peak_db)


def timeline(path):
    with open(path, encoding="utf-8") as handle:
        raw = json.load(handle)
    analysis = raw["analysis"]
    if analysis.get("engine") == "placeholder":
        return []
    notes = [note for lesson in analysis["lessons"] for note in lesson["notes"]]
    notes = [
        {
            "pitch": str(note["pitch"]),
            "startTime": float(note["startTime"]),
            "duration": float(note["duration"]),
            "intensity": float(note["intensity"]),
        }
        for note in notes
        if float(note["startTime"]) >= 0 and float(note["duration"]) > 0
    ]
    notes.sort(key=lambda note: note["startTime"])
    return analysis, notes


def write(path, text):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    print("wrote", path, f"({len(text) / 1024:.0f} KB)")


def main():
    samples, rate = decode(SOURCE_MP3)
    average_db, peak_db = envelope(samples, rate)
    print(f"frames: {len(average_db)} ({len(average_db) / FRAME_RATE:.2f} s)")

    analysis, notes = timeline(SOURCE_ANALYSIS)
    print(f"notes: {len(notes)}")

    print(
        "average dB — min %.1f  p10 %.1f  median %.1f  p90 %.1f  max %.1f"
        % (
            min(average_db),
            float(np.percentile(average_db, 10)),
            float(np.percentile(average_db, 50)),
            float(np.percentile(average_db, 90)),
            max(average_db),
        )
    )

    payload = {
        "title": analysis.get("title", "两只老虎"),
        "id": "liang-zhi-lao-hu",
        "bpm": analysis.get("bpm"),
        "key": analysis.get("key"),
        "engine": analysis.get("engine"),
        "duration": analysis.get("duration"),
        "frameRate": FRAME_RATE,
        "notes": notes,
        "averageDB": average_db,
        "peakDB": peak_db,
    }

    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    write(
        os.path.join(ROOT, "data", "song-data.js"),
        "// Generated by scripts/generate-data.py — do not edit by hand.\n"
        "// Note timeline from the voice project's published analysis, energy\n"
        "// envelope measured from the recording at 60 frames per second.\n"
        f"window.SONG_DATA = {body};\n",
    )

    with open(SOURCE_MP3, "rb") as handle:
        encoded = base64.b64encode(handle.read()).decode("ascii")
    write(
        os.path.join(ROOT, "data", "audio-data.js"),
        "// Generated by scripts/generate-data.py — do not edit by hand.\n"
        "// Offline fallback for browsers that refuse a relative media file on a\n"
        "// file:// page. Loaded only when the plain <audio> source fails.\n"
        f"window.SONG_AUDIO_DATA_URI = \"data:audio/mpeg;base64,{encoded}\";\n",
    )
    os.remove(WORK_WAV)


if __name__ == "__main__":
    sys.exit(main())
